namespace ITSchoolCRM.API.Caching;

/// <summary>
/// Времена жизни кэша по категориям данных.
/// Значения заполняются один раз в Program.cs из секции
/// "Cache" appsettings.json и дальше только читаются.
/// Сервисы получают этот объект через DI (Singleton).
/// </summary>
public sealed class CacheOptions
{
    /// <summary>
    /// Справочники: вузы, направления, программы, продукты, пользователи.
    /// Меняются редко → длинный TTL (по умолчанию 600 секунд).
    /// При любом изменении справочника версия инкрементируется,
    /// кэш сбрасывается досрочно — TTL служит лишь подстраховкой.
    /// </summary>
    public TimeSpan CatalogTtl { get; init; }

    /// <summary>
    /// Карточки взаимодействий, история статусов, вложения, workflow.
    /// Инвалидируются при любом изменении данных (по умолчанию 300 секунд).
    /// </summary>
    public TimeSpan InteractionTtl { get; init; }

    /// <summary>
    /// Агрегаты статистики (дашборд, визуализация).
    /// Короткий TTL (по умолчанию 60 секунд): лёгкая расхождённость
    /// счётчиков в течение минуты допустима, зато дашборд летает.
    /// </summary>
    public TimeSpan StatisticsTtl { get; init; }
}