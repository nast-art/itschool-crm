export default function DocumentationPage() {
  const { user } = useAuth()

  // Ролевая модель (п. 11 ТЗ): переключатель «Администратору» — только
  // admin; глава о привилегиях руководителя — manager и admin.
  const roles = user?.roles ?? []
  const isAdmin = roles.includes('admin')
  const isPrivileged = isAdmin || roles.includes('manager')

  const userChapters = useMemo(
    () =>
      isPrivileged
        ? [
            ...USER_GUIDE.chapters.slice(0, 5),
            MANAGER_CHAPTER,
            ...USER_GUIDE.chapters.slice(5),
          ]
        : USER_GUIDE.chapters,
    [isPrivileged],
  )

  const guides = useMemo(() => {
    const list = [{ ...USER_GUIDE, chapters: userChapters }]
    if (isAdmin) list.push(ADMIN_GUIDE)
    return list
  }, [isAdmin, userChapters])

  // Активное руководство и активная глава (по умолчанию — первые)
  const [activeGuideId, setActiveGuideId] = useState('user')
  const [activeChapterId, setActiveChapterId] = useState('login')
  const [query, setQuery] = useState('')

  // Область контента — свой скролл (фиксированная высота ридера).
  // При смене главы/руководства прокрутка контента сбрасывается наверх.
  const contentRef = useRef(null)

  function scrollContentTop() {
    if (contentRef.current) {
      contentRef.current.scrollTop = 0
    }
  }

  const activeGuide =
    guides.find((g) => g.id === activeGuideId) ?? guides[0]

  // Быстрый поиск: фильтрует СПИСОК ГЛАВ в меню по заголовкам и тексту
  const normalizedQuery = query.trim().toLowerCase()
  const visibleChapters = useMemo(() => {
    if (!normalizedQuery) return activeGuide.chapters
    return activeGuide.chapters.filter(
      (chapter) =>
        chapter.title.toLowerCase().includes(normalizedQuery) ||
        chapter.blocks.some(
          (block) =>
            (block.text ?? '')
              .toLowerCase()
              .includes(normalizedQuery) ||
            (block.items ?? []).some((item) =>
              item.toLowerCase().includes(normalizedQuery),
            ),
        ),
    )
  }, [activeGuide, normalizedQuery])

  // Текущая глава: если поиск её скрыл — показываем пустое состояние
  const activeChapter = visibleChapters.find(
    (c) => c.id === activeChapterId,
  )
  const activeIndex = visibleChapters.findIndex(
    (c) => c.id === activeChapterId,
  )
  const prevChapter =
    activeIndex > 0 ? visibleChapters[activeIndex - 1] : null
  const nextChapter =
    activeIndex >= 0 && activeIndex < visibleChapters.length - 1
      ? visibleChapters[activeIndex + 1]
      : null

  // Смена руководства: открываем его первую главу
  function switchGuide(id) {
    setActiveGuideId(id)
    setQuery('')
    const guide = guides.find((g) => g.id === id)
    if (guide?.chapters[0]) {
      setActiveChapterId(guide.chapters[0].id)
    }
    scrollContentTop()
  }

  // Выбор главы в левом меню — открывает её одну
  function selectChapter(id) {
    setActiveChapterId(id)
    scrollContentTop()
  }

  return (
    <div className="dashboard">
      {/* ---------- Шапка ---------- */}
      <div className="page-head">
        <div>
          <h1>Документация</h1>
          <p className="page-sub">Руководства и пошаговые инструкции</p>
        </div>
      </div>

      {/* ---------- Каркас ридера: меню и контент независимо
           скроллятся внутри фиксированной по высоте области ---------- */}
      <div className="docs-layout">
        {/* ===== ЛЕВОЕ МЕНЮ ===== */}
        <aside className="docs-toc" aria-label="Меню документации">
          {/* Переключатель руководств. У администратора две вкладки,
              у остальных ролей — одна (п. 11 ТЗ) */}
          {guides.length > 1 && (
            <div
              className="docs-toc-tabs"
              role="tablist"
              aria-label="Руководство"
            >
              {guides.map((guide) => (
                <button
                  key={guide.id}
                  type="button"
                  role="tab"
                  aria-selected={guide.id === activeGuideId}
                  className={
                    guide.id === activeGuideId
                      ? 'docs-toc-tab is-active'
                      : 'docs-toc-tab'
                  }
                  onClick={() => switchGuide(guide.id)}
                >
                  {guide.id === 'admin' ? (
                    <IconGear size={15} />
                  ) : (
                    <IconBook size={15} />
                  )}
                  <span>{guide.tabLabel}</span>
                </button>
              ))}
            </div>
          )}

          {/* Поиск по главам */}
          <div className="docs-toc-search">
            <IconSearch size={15} />
            <input
              type="text"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Найти в руководстве…"
              aria-label="Поиск по руководству"
            />
          </div>

          {/* Список глав — нажатие ОТКРЫВАЕТ главу справа */}
          <div className="docs-toc-title">Содержание</div>
          <nav>
            {visibleChapters.length === 0 ? (
              <p className="docs-toc-empty">Ничего не найдено</p>
            ) : (
              visibleChapters.map((chapter) => (
                <button
                  key={chapter.id}
                  type="button"
                  className={
                    chapter.id === activeChapterId
                      ? 'docs-toc-link is-active'
                      : 'docs-toc-link'
                  }
                  onClick={() => selectChapter(chapter.id)}
                >
                  <chapter.icon size={15} />
                  <span>{chapter.title}</span>
                </button>
              ))
            )}
          </nav>
        </aside>

        {/* ===== КОНТЕНТ: открыта РОВНО ОДНА глава ===== */}
        <div className="docs-content" ref={contentRef}>
          {/* Описание активного руководства */}
          <div className="docs-intro">
            <h2>{activeGuide.intro.title}</h2>
            <p>{activeGuide.intro.description}</p>
          </div>

          {visibleChapters.length === 0 || !activeChapter ? (
            <section className="panel">
              <p className="empty">
                По запросу «{query}» ничего не найдено. Попробуйте другие
                слова, например «workflow», «отчёт» или «файл» — или{' '}
                <button
                  type="button"
                  className="docs-reset-link"
                  onClick={() => {
                    setQuery('')
                    setActiveChapterId(activeGuide.chapters[0].id)
                  }}
                >
                  сбросить поиск
                </button>
                .
              </p>
            </section>
          ) : (
            <>
              <GuideChapter chapter={activeChapter} />

              {/* Листание глав без возврата в меню */}
              <nav
                className="docs-chapter-nav"
                aria-label="Листание глав"
              >
                {prevChapter ? (
                  <button
                    type="button"
                    className="docs-chapter-nav-btn"
                    onClick={() => selectChapter(prevChapter.id)}
                  >
                    <span className="docs-chapter-nav-dir">← Назад</span>
                    <span className="docs-chapter-nav-title">
                      {prevChapter.title}
                    </span>
                  </button>
                ) : (
                  <span
                    className="docs-chapter-nav-btn is-disabled"
                    aria-hidden="true"
                  />
                )}
                {nextChapter ? (
                  <button
                    type="button"
                    className="docs-chapter-nav-btn is-next"
                    onClick={() => selectChapter(nextChapter.id)}
                  >
                    <span className="docs-chapter-nav-dir">Далее →</span>
                    <span className="docs-chapter-nav-title">
                      {nextChapter.title}
                    </span>
                  </button>
                ) : (
                  <span
                    className="docs-chapter-nav-btn is-disabled"
                    aria-hidden="true"
                  />
                )}
              </nav>
            </>
          )}
        </div>
      </div>

      {/* ---------- Архитектура решения ---------- */}
      <section className="panel">
        <h2>Архитектура решения</h2>
        <p className="panel-sub">
          Функциональная и компонентная архитектура CRM (подробное
          описание в Archi — см. сопроводительную документацию,
          п. 7 требований к решению)
        </p>
        <div className="arch-grid">
          {ARCHITECTURE_COMPONENTS.map((component) => (
            <article key={component.title} className="arch-card">
              <div className="arch-card-head">
                <span
                  className="arch-card-icon"
                  aria-hidden="true"
                >
                  <component.icon size={20} />
                </span>
                <h3>{component.title}</h3>
              </div>
              <p>{component.text}</p>
            </article>
          ))}
        </div>
      </section>

      {/* ---------- Коды ошибок (нефункциональное требование 3 ТЗ) ---------- */}
      <section className="panel">
        <h2>Коды ошибок</h2>
        <p className="panel-sub">
          Единый формат ответа об ошибке: ErrorResponseDto{' '}
          {'{ code, message }'}. Код ошибки показывается в интерфейсе
          рядом с описанием проблемы.
        </p>
        <div className="table-wrap">
          <table className="codes-table">
            <thead>
              <tr>
                <th>Код</th>
                <th>Внутренний код</th>
                <th>Описание</th>
                <th>Действие</th>
              </tr>
            </thead>
            <tbody>
              {ERROR_CODES.map((error) => (
                <tr key={error.name}>
                  <td className="codes-code">{error.code}</td>
                  <td className="codes-name">{error.name}</td>
                  <td>{error.description}</td>
                  <td>{error.action}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  )
}