// Иллюстрация экрана: реальный скриншот (src) с автоматическим
// возвратом к встроенной SVG-схеме, если файл не найден или src
// не задан (как у админских иллюстраций, снимки которых пока
// не сделаны).
function GuideImage({ shot, src, caption }) {
  const [imageFailed, setImageFailed] = useState(false)
  const Illustration = shot ? DOC_SCREENSHOTS[shot] : null

  return (
    <figure className="doc-figure">
      {src && !imageFailed ? (
        <img
          className="doc-figure-img"
          src={src}
          alt={caption}
          loading="lazy"
          onError={() => setImageFailed(true)}
        />
      ) : (
        <div className="doc-figure-illustration">
          {Illustration ? <Illustration /> : null}
        </div>
      )}
      <figcaption>{caption}</figcaption>
    </figure>
  )
}

function GuideBlock({ block }) {
  if (block.type === 'p') {
    return <p className="doc-p">{block.text}</p>
  }
  if (block.type === 'steps') {
    return (
      <ol className="doc-steps">
        {block.items.map((item, index) => (
          <li key={index}>{item}</li>
        ))}
      </ol>
    )
  }
  if (block.type === 'image') {
    return (
      <GuideImage
        shot={block.shot}
        src={block.src}
        caption={block.caption}
      />
    )
  }
  if (block.type === 'note') {
    return <p className="doc-note">{block.text}</p>
  }
  return null
}

// Глава — всегда развёрнута (без аккордеона): заголовок с иконкой + блоки.
function GuideChapter({ chapter }) {
  return (
    <section className="doc-chapter">
      <div className="doc-chapter-head">
        <span className="doc-chapter-icon" aria-hidden="true">
          <chapter.icon size={18} />
        </span>
        <h3>{chapter.title}</h3>
      </div>
      <div className="doc-chapter-body">
        {chapter.blocks.map((block, index) => (
          <GuideBlock key={index} block={block} />
        ))}
      </div>
    </section>
  )
}

